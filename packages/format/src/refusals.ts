// Every place that refuses an edit, and what becomes of it (format §3.12, hardening.md): the policy of
// Redlines is not to refuse. An edit that no fine form writes soundly is widened to the unit that
// holds it, one that no unit can hold is made untracked after the person is asked, a command that
// never makes sense is disabled, and only where every write would leave the file wrong is a refusal
// kept. This file says which of the four each refusal is, so that "never add a refusal" is held by a
// test and not by a note: `refusals.node.test.ts` reads the sources and fails when a place that
// refuses has no tier here.
//
// A refusal is found by its file and the first words of its message (or the name of the constant
// that holds it): the same refusal in another place of the file has the same tier. A new one is
// given its tier when it is added: a refusal that can be widened is widened, not listed here.
//
// The tiers of the rows that the refusal inventory of the Epic names (190 distinct refusals) are its
// tiers; the rest, which it did not count (the notices of the plugins, and the errors that carry a
// message made at the place), are given by the code of the error or by what the notice says.

import type { EditErrorCode } from './errors.ts';

/** What becomes of a refusal. `info` is no refusal: a notice that tells, or shows an error that
 * has its own tier. */
export type RefusalTier = 'widen' | 'alert' | 'disable' | 'keep' | 'info';

/** A refusal: the file, the key of its message, its tier, and why. */
export type RefusalEntry = readonly [file: string, key: string, tier: RefusalTier, why: string];

/**
 * The error codes that stay refusals: where any write would leave the file wrong, or the
 * argument is wrong (design §5). Every other code is widened, or asked about, or disabled.
 */
export const KEPT_CODES: readonly EditErrorCode[] = [
  'unreadable-ledger',
  'unclosed-end',
  'markup',
  'unknown-id',
  'no-match',
  'many-matches',
];

/** What becomes of an edit that the fine writer refused, from the code of its error. */
export function tierOfCode(code: EditErrorCode | undefined): RefusalTier {
  if (code === undefined) return 'keep';
  if (KEPT_CODES.includes(code)) return 'keep';
  if (code === 'front-matter') return 'alert';
  if (code === 'not-supported') return 'disable';
  return 'widen';
}

